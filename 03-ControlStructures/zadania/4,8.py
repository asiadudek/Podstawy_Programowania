# Calculates values for the following fractions: 1/2, 1/3, ..., 1/10
#
for u in range(1,11): #petla sprawdza nam kazda cyfre czyli "u" z przedzialu od 1 do 10
    print(f"1/{u} = {1/u}") #w drugiej klamerce mamy dzialanie a w pierwszej wpisalismy "u" aby petla wyswietlila nam wszystkie ulamki od 1/1 do 1/10